assert.match(source, /\.player-table \.tr> :nth-child\(7\)::before\{display:block!important/)
assert.match(source, /rangeLimited && tab !== 'history'/)
assert.match(source, /<section v-if="hasAnalytics && !rangeLimited" class="summary-strip">/)
assert.match(source, /本时间范围对局过多，暂无法显示完整排行。请切换本赛季。/)
