import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import ts from 'typescript'

const source = readFileSync(new URL('../src/l12/site/RankingsPage.vue', import.meta.url), 'utf8')
const endpoint = readFileSync(new URL('../../服务端WebSocket/TwelveLegions/L12WebSocketServer.cs', import.meta.url), 'utf8')
const logic = source.slice(source.indexOf('let disposed ='), source.indexOf('const query ='))
const code = ts.transpileModule(logic, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText
let nextTimer = 0
const timers = new Map()
const document = { hidden: false }
const requests = []
const rankedApi = { leaderboard(faction, range) { return new Promise((resolve, reject) => requests.push({ faction, range, resolve, reject })) }, history: async () => ({ honors: [], factionTotals: [] }) }
const state = Object.fromEntries(['faction','range','tab','loading','error','players','analytics','history','rangeLimited','hasAnalytics'].map(k => [k, { value: k === 'range' ? 'season' : k === 'tab' ? 'players' : ['loading','rangeLimited','hasAnalytics'].includes(k) ? false : k === 'history' ? { honors: [], factionTotals: [] } : '' }]))
const api = new Function(...Object.keys(state), 'rankedApi', 'document', 'setTimeout', 'clearTimeout', `${code}; return {load,dispose(){disposed=true}}`)(
  ...Object.values(state), rankedApi, document, (fn, delay) => { const id = ++nextTimer; timers.set(id, {fn,delay}); return id }, id => timers.delete(id))
const response = label => ({ players: [label], analytics: { label } })
const flush = async () => { for (let i=0;i<8;i++) await Promise.resolve() }
void api.load()
assert.equal(requests.length, 1)
state.range.value = '7d'
void api.load()
assert.equal(requests.length, 1, 'no overlapping requests')
requests[0].resolve(response('stale'))
await flush()
assert.equal(requests.length, 2)
assert.equal(requests[1].range, '7d')
assert.notDeepEqual(state.players.value, ['stale'])
requests[1].resolve(response('fresh'))
await flush()
assert.deepEqual(state.players.value, ['fresh'])
assert.equal(state.hasAnalytics.value, true, 'successful explicit read makes analytics available')
assert.equal(timers.size, 0, 'settled ranking never schedules another request')
document.hidden = true
assert.equal(timers.size, 0)
document.hidden = false
await flush()
assert.equal(requests.length, 2, 'visibility alone never refreshes ranking')
void api.load()
assert.equal(requests.length, 3)
requests[2].reject(new Error('offline'))
await flush()
assert.deepEqual(state.players.value, ['fresh'], 'failure retains last good snapshot')
assert.equal(state.error.value, 'offline')
assert.equal(timers.size, 0, 'failure waits for explicit retry; no hidden automatic request')
state.range.value = '30d'
void api.load()
assert.equal(requests.length, 4)
requests[3].resolve({ ...response('capped'), players: [], rangeLimited: true })
await flush()
assert.equal(state.rangeLimited.value, true, 'capped range is explicit instead of a partial leaderboard')
assert.deepEqual(state.players.value, [])
state.tab.value = 'history'
void api.load()
assert.equal(requests.length, 5, 'switching ranking item explicitly refreshes')
requests[4].resolve(response('history-selected'))
await flush()
assert.deepEqual(state.players.value, ['history-selected'])
state.faction.value = 'order'
void api.load()
state.faction.value = ''
void api.load()
assert.equal(requests.length, 6, 'rapid selection changes retain one in-flight read')
requests[5].resolve(response('aba-stale'))
await flush()
assert.notDeepEqual(state.players.value, ['aba-stale'], 'an intermediate selection cannot repaint the latest one')
assert.equal(requests.length, 7, 'only latest queued selection starts next')
requests[6].resolve(response('aba-fresh'))
await flush()
assert.deepEqual(state.players.value, ['aba-fresh'])
void api.load()
assert.equal(requests.length, 8)
api.dispose()
requests[7].resolve(response('unmounted'))
await flush()
assert.deepEqual(state.players.value, ['aba-fresh'], 'late read after unmount cannot replace snapshot')
assert.equal(timers.size, 0)
await api.load()
assert.equal(requests.length, 8)
